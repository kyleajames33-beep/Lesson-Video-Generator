import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import ts from 'typescript';
const modelSource=await readFile(new URL('./model.ts',import.meta.url),'utf8');
const js=ts.transpileModule(modelSource,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext}}).outputText;
const m=await import(`data:text/javascript;base64,${Buffer.from(js).toString('base64')}`);
assert.equal(m.hubbleVelocity(100),7000);
assert.equal(m.scaleFactor(-1),1); assert.equal(m.scaleFactor(2),2.5);
assert.equal(m.hydrogenEnergy(1),-13.6);
assert.ok(Math.abs(1240/(m.hydrogenEnergy(3)-m.hydrogenEnergy(2))-656.47)<1);
for(let t=0;t<=4;t+=.1)assert.ok(m.remaining(t)>=0&&m.remaining(t)<=1);
assert.equal(m.remaining(1),.5); assert.equal(m.remaining(4),.0625);
assert.ok(Math.abs(m.quarkCharge(['u','u','d'])-1)<1e-12);
assert.ok(Math.abs(m.quarkCharge(['u','d','d']))<1e-12);
assert.equal(new Set(m.decayTimes).size,80);
assert.equal(m.decayTimes.filter(t=>t>1).length,40);
assert.equal(m.decayTimes.filter(t=>t>2).length,20);
assert.ok(m.bindingCurve.find(([a])=>a===62)[1]>m.bindingCurve.find(([a])=>a===56)[1]);
const source=await readFile(new URL('./index.tsx',import.meta.url),'utf8');
assert.ok(!source.includes('\u2014'));
assert.ok(!/Math\.random|Date\.now|useCurrentFrame|setInterval/.test(source));
const ids=[...source.matchAll(/id:'(m8-[^']+)'/g)].map(v=>v[1]);
assert.equal(ids.length,10);assert.equal(new Set(ids).size,10);
const mapped=[...source.matchAll(/siteLessons:\[([^\]]+)\]/g)].flatMap(v=>v[1].split(',').map(Number));
assert.deepEqual([...new Set(mapped)].sort((a,b)=>a-b),m.siteLessonNumbers);
const diagnostics=ts.transpileModule(source,{compilerOptions:{jsx:ts.JsxEmit.React,target:ts.ScriptTarget.ES2022},reportDiagnostics:true}).diagnostics??[];
assert.equal(diagnostics.filter(d=>d.category===ts.DiagnosticCategory.Error).length,0);
console.log('Module 8: 10 unique families, all 17 site pages mapped; physical model and deterministic-source invariants passed.');
console.log('Source checks do not approve visual layout, motion at playback speed or complete teaching coverage.');
