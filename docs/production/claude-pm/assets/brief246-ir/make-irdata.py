"""Build src/explainer/lessons/chem-m8-c10/irdata.ts from the measured point CSVs: each trace binned to 5 cm-1, keeping
the lowest and highest %T point of every bin (so narrow dips keep their depth), 4000 to 450 cm-1."""
import csv, json, sys
from pathlib import Path
R=Path(__file__).resolve().parents[5]
A=R/'docs/production/claude-pm/assets'
SRC={
 'cyclohexane':(A/'brief120-nist/cyclohexane-ir-points.csv','NIST Coblentz 6045, neat liquid'),
 'tBuOH':(A/'brief120-nist/tert-butanol-ir-points.csv','NIST Coblentz 6880, neat liquid'),
 'butan1ol':(A/'brief120-nist/butan-1-ol-ir-points.csv','NIST Coblentz 6915, neat liquid'),
 'ethanol':(A/'brief246-ir/ethanol-ir-points.csv','J18-E JP XVIII anhydrous ethanol, liquid film'),
 'propylamine':(A/'brief246-ir/propan-1-amine-ir-points.csv','JFA p51 propylamine, liquid film'),
 'propan1ol':(A/'brief246-ir/propan-1-ol-ir-points.csv','JFA p50, liquid film'),
 'propan2ol':(A/'brief246-ir/propan-2-ol-ir-points.csv','JFA p31, liquid film'),
 'ethylEthanoate':(A/'brief246-ir/ethyl-ethanoate-ir-points.csv','CAA-EA ethyl acetate, liquid film'),
 'ethylPropanoate':(A/'brief246-ir/ethyl-propanoate-ir-points.csv','JFA p22, liquid film'),
 'ethanoicAcid':(A/'brief246-ir/ethanoic-acid-a306-ir-points.csv','A306-IR SDBS 306 IR-NIDA-60820, liquid film (digitised 16 Nov)'),
 'propanone':(A/'brief246-ir/propanone-a319-ir-points.csv','A319-IR SDBS 319 IR-NIDA-63533, liquid film (digitised 16 Nov)'),
 'methylMethanoate':(A/'brief246-ir/methyl-methanoate-a1208-ir-points.csv','A1208-IR SDBS 1208 IR-NIDA-20626, liquid film (digitised 16 Nov; record ends near 760)'),
 'butanone':(A/'brief246-ir/butanone-mek-ir-points.csv','MEK-IR experimental liquid film (digitised 16 Nov)'),
}
out=['// GENERATED by docs/production/claude-pm/assets/brief246-ir/make-irdata.py from measured point files. Do not edit.',
     '// Each trace: [wavenumber cm-1, transmittance %] pairs, 4000 to 450, binned to 5 cm-1 (lowest and highest point per bin).',
     'export type IRPts = [number, number][];','export const IR_SRC: Record<string, string> = '+json.dumps({k:v[1] for k,v in SRC.items()})+';']
for k,(p,_) in SRC.items():
    pts=[]
    for row in open(p):
        if row.startswith('#') or row.startswith('wave'): continue
        w,t=map(float,row.split(',')[:2])
        if 450<=w<=4000: pts.append((w,t))
    pts.sort(key=lambda q:-q[0])
    bins={}
    for w,t in pts: bins.setdefault(int(w//5),[]).append((w,t))
    seq=[]
    for b in sorted(bins,reverse=True):
        g=bins[b]; lo=min(g,key=lambda q:q[1]); hi=max(g,key=lambda q:q[1])
        sel=sorted({lo,hi},key=lambda q:-q[0])
        seq+=sel
    out.append(f'export const IR_{k}: IRPts = '+json.dumps([[round(w,1),round(t,1)] for w,t in seq],separators=(',',':'))+';')
    print(k,len(seq),min(seq,key=lambda q:q[1]))
(R/'src/explainer/lessons/chem-m8-c10').mkdir(parents=True,exist_ok=True)
(R/'src/explainer/lessons/chem-m8-c10/irdata.ts').write_text('\n'.join(out)+'\n',encoding='utf8')
